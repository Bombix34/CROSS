// Generates the lookup tables shared by the C engine and the Node preview.
// Usage: node tools/gen_tables.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FS = 44100;
const round = Math.round;
const clamp = (x, lo, hi) => Math.min(hi, Math.max(lo, x));

// Soft clipper: input Q13 over [-4, 4], output Q15.
const tanh = Array.from({ length: 257 }, (_, k) =>
  round(32767 * Math.tanh((k * 256 - 32768) / 8192)));

// log2(1 + i/64) in Q16.
const log2 = Array.from({ length: 65 }, (_, i) => round(65536 * Math.log2(1 + i / 64)));

// One-pole coefficient for cutoff = 20 Hz * 2^(k/16), Q15, capped near 13 kHz.
const G_MAX = 27525;
const gcoef = Array.from({ length: 161 }, (_, k) => {
  const fc = 20 * 2 ** (k / 16);
  return Math.min(G_MAX, round(32768 * (1 - Math.exp(-2 * Math.PI * fc / FS))));
});

// Contour decay per 16-sample step, Q16: 5 ms to 2 s, exponential knob.
const decay = Array.from({ length: 129 }, (_, i) => {
  const tau = 0.005 * 400 ** (i / 128);
  return Math.min(65535, round(65536 * (1 - Math.exp(-16 / (tau * FS)))));
});
const ATTACK = round(65536 * (1 - Math.exp(-16 / (0.0015 * FS))));

// VCO2 pitch ratio, Q16, nearest index (p >> 8): 0-25 cents, then a fifth, then an octave.
const detune = Array.from({ length: 128 }, (_, i) => {
  let cents;
  if (i < 96) cents = 25 * (i / 96) ** 2;
  else if (i < 112) cents = 703;
  else cents = 1203;
  return round(65536 * 2 ** (cents / 1200));
});

// DRIVE macro: pre-filter gain (Q16), post-filter gain (Q8, 0 = bypass), output level (Q15),
// attack punch (Q15: how far the filter contour lifts the level after the post drive).
const PRE_LO = 3277, PRE_HI = 19660;
const drivePre = [], drivePost = [], driveOut = [], drivePunch = [];
for (let i = 0; i <= 128; i++) {
  const d = i / 128;
  const a = clamp(d / 0.5, 0, 1);
  const b = clamp((d - 0.5) / 0.5, 0, 1);
  const pre = PRE_LO * (PRE_HI / PRE_LO) ** a;
  const post = b > 0 ? 256 * 16 ** b : 0;
  // Level: keep the mixer overload roughly steady; let the post drive grow louder, a squared wave
  // held at a steady level sounds flat.
  const preLoud = Math.tanh(0.5 * pre / PRE_LO) / Math.tanh(0.5);
  const postLoud = b > 0 ? Math.tanh(post / 256 * 0.6) / 0.6 : 1;
  drivePre.push(round(pre));
  drivePost.push(round(post));
  driveOut.push(round(clamp(24576 / (preLoud ** 0.7 * postLoud ** 0.45), 4096, 32767)));
  // Punch: the clipper flattens every transient, so past the middle each note's attack is lifted
  // back above the body, up to +4.6 dB at full DRIVE, fading with the contour (DECAY).
  drivePunch.push(round(22937 * b ** 1.5));
}

// C2 (65.406 Hz) as the key-tracking reference, as log2 of the phase increment in Q16.
const LOG2_REF = round(65536 * Math.log2(65.406 / FS * 2 ** 32));

const tables = { tanh, log2, gcoef, decay, detune, drivePre, drivePost, driveOut, drivePunch, ATTACK, LOG2_REF, G_MAX };
writeFileSync(join(root, 'tools', 'tables.json'), JSON.stringify(tables));

const arr = (type, name, v) => {
  const rows = [];
  for (let i = 0; i < v.length; i += 12) rows.push('    ' + v.slice(i, i + 12).join(', '));
  return `static const ${type} ${name}[${v.length}] = {\n${rows.join(',\n')}\n};\n`;
};

writeFileSync(join(root, 'cross', 'cross_tables.h'), `/* Generated by tools/gen_tables.mjs - do not edit by hand. */
#ifndef CROSS_TABLES_H
#define CROSS_TABLES_H

#include <stdint.h>

#define TCH_ATTACK_COEF ${ATTACK}
#define TCH_LOG2_REF ${LOG2_REF}
#define TCH_G_MAX ${G_MAX}

${arr('int16_t', 'tch_tanh', tanh)}
${arr('int32_t', 'tch_log2', log2)}
${arr('int16_t', 'tch_gcoef', gcoef)}
${arr('uint16_t', 'tch_decay', decay)}
${arr('uint32_t', 'tch_detune', detune)}
${arr('int32_t', 'tch_drive_pre', drivePre)}
${arr('int32_t', 'tch_drive_post', drivePost)}
${arr('int16_t', 'tch_drive_out', driveOut)}
${arr('int16_t', 'tch_drive_punch', drivePunch)}
#endif
`);
console.log('tables written');
